E8_METHODOLOGY_VERSION = "e8-v1"

BASELINE_SEMANTICS = (
    "Current Reference/Baseline Fields from Imported Schedule — "
    "not a contractual baseline until BaselineVersion exists."
)
DATA_DATE_SEMANTICS = (
    "Metrics computed as-of ScheduleSource.data_date when present; else system date."
)
LIVE_STATE = AnalyticalState.LIVE_CURRENT.value
REIMPORT_CAVEAT = "Results may change after schedule or model re-import because no frozen analytical snapshot is selected."


def _def(
    metric_id: str,
    label: str,
    business_question: str,
    formula: str,
    numerator: str,
    denominator: str,
    *,
    weighting: str = "none",
    source: str,
    source_authority: str,
    inclusion: str,
    exclusion: str,
    missing: str = "Report unavailable with reason — never fabricate values.",
    coverage_metric: str = "",
    authority: str = MetricAuthority.DERIVED.value,
    caveat: str = "",
    drilldown: str = "executive_controls_delays",
    drilldown_filter: dict[str, str] | None = None,
    filters: tuple[str, ...] = (),
) -> E8MetricDefinition:
    return E8MetricDefinition(
        metric_id=metric_id,
        label=label,
        business_question=business_question,
        formula=formula,
        numerator_definition=numerator,
        denominator_definition=denominator,
        weighting_method=weighting,
        primary_source=source,
        source_authority=source_authority,
        inclusion_rules=inclusion,
        exclusion_rules=exclusion,
        baseline_semantics=BASELINE_SEMANTICS,
        data_date_semantics=DATA_DATE_SEMANTICS,
        missing_data_behavior=missing,
        coverage_metric=coverage_metric,
        authority_level=authority,
        caveat=caveat or REIMPORT_CAVEAT,
        drilldown_route=drilldown,
        drilldown_filter=drilldown_filter or {},
        compatible_filters=filters,
        version=E8_METHODOLOGY_VERSION,
    )


