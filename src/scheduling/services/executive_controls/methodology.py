def build_e8_metric_result(
    definition: E8MetricDefinition,
    *,
    available: bool,
    value: int | float | None = None,
    unit: str = "count",
    numerator: int | float | None = None,
    denominator: int | float | None = None,
    authority: str | None = None,
    coverage: dict[str, Any] | None = None,
    caveats: list[str] | None = None,
    data_date: str | None = None,
    calculated_at: str | None = None,
) -> E8MetricResult:
    """Build a metric result; percentage only when denominator is positive."""
    pct: float | None = None
    if denominator is not None and denominator > 0 and numerator is not None:
        pct = round(100.0 * float(numerator) / float(denominator), 2)
    return E8MetricResult(
        metric_id=definition.metric_id,
        label=definition.label,
        available=available,
        value=value if value is not None else numerator,
        unit=unit,
        numerator=numerator,
        denominator=denominator,
        percentage=pct,
        source=definition.primary_source,
        authority=authority or definition.authority_level,
        methodology_version=E8_METHODOLOGY_VERSION,
        coverage=coverage,
        caveats=caveats or ([definition.caveat] if definition.caveat else []),
        data_date=data_date,
        calculated_at=calculated_at or datetime.now(UTC).isoformat(),
        analytical_state=LIVE_STATE,
        drilldown_route=definition.drilldown_route,
        drilldown_filter=dict(definition.drilldown_filter),
    )


def methodology_registry_payload() -> list[dict[str, Any]]:
    """Export all e8-v1 definitions for API/UI methodology drawer."""
    return [d.to_dict() for d in E8_METRIC_REGISTRY.values()]
